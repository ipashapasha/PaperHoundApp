// Unit and instrumented test coverage in one report; needs a connected device or emulator.
tasks.register<JacocoReport>("jacocoDebugReport") {
    group = "verification"
    description = "Merged unit and instrumented test coverage for the debug build."
    dependsOn("testDebugUnitTest", "connectedDebugAndroidTest")

    // Generated by Room and the Android build, not code written in this project.
    val generated = listOf("**/R.class", "**/R$*.class", "**/BuildConfig.*", "**/Manifest*.*", "**/*_Impl*.*")
    val build = layout.buildDirectory
    classDirectories.setFrom(
        build.dir("intermediates/built_in_kotlinc/debug/compileDebugKotlin/classes").map { fileTree(it) { exclude(generated) } },
    )
    sourceDirectories.setFrom("src/main/java")
    executionData.setFrom(
        build.file("outputs/unit_test_code_coverage/debugUnitTest/testDebugUnitTest.exec"),
        build.dir("outputs/code_coverage/debugAndroidTest/connected").map { fileTree(it) { include("**/*.ec") } },
    )
    reports {
        xml.required = true
        html.required = true
    }
}

