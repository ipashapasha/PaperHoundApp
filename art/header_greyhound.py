"""Generates the home header illustration (res/drawable/header_greyhound.xml).

Run from the repo root: python3 art/header_greyhound.py
"""
W, H = 360, 100

def ellipse(cx, cy, rx, ry):
    return f"M{cx-rx},{cy} a{rx},{ry} 0 1,0 {2*rx},0 a{rx},{ry} 0 1,0 {-2*rx},0 Z"

# Pastel palette
FUR, FUR_DARK, FUR_LIGHT = "#EBC9A6", "#D2A782", "#F6E3CF"
INK = "#5B4636"
MINT, MINT_DARK = "#A8DCC9", "#8BC7B2"
BALL, BALL_SEAM = "#E6EE9C", "#FFFFFF"
CLOUD, SUN, PINK = "#F7DCD3", "#FBE3A6", "#F4A9A8"

E = []  # (kind, d, color, extra)
def fill(d, c, a=1.0): E.append(("fill", d, c, a))
def stroke(d, c, w, a=1.0): E.append(("stroke", d, c, (w, a)))

# Background: sun, clouds, hills
fill(ellipse(326, 22, 11, 11), SUN)
fill("M18,30 a8,8 0 0,1 14,-6 a10,10 0 0,1 18,2 a7,7 0 0,1 4,12 L22,38 a6,6 0 0,1 -4,-8 Z", CLOUD)
fill("M236,20 a7,7 0 0,1 12,-5 a9,9 0 0,1 16,2 a6,6 0 0,1 3,10 L240,27 a5,5 0 0,1 -4,-7 Z", CLOUD, 0.8)
fill("M0,86 C50,78 110,82 170,85 C230,88 290,78 360,84 L360,100 L0,100 Z", MINT)
fill("M0,92 C70,88 140,94 220,91 C280,89 320,93 360,90 L360,100 L0,100 Z", MINT_DARK)

# Ground shadows
fill(ellipse(150, 88, 46, 2.6), INK, 0.10)
fill(ellipse(304, 88, 9, 1.8), INK, 0.10)

# Speed lines behind the dog
for (x1, y, x2) in [(34, 40, 58), (24, 52, 54), (40, 64, 60)]:
    stroke(f"M{x1},{y} L{x2},{y}", FUR_DARK, 2.4, 0.55)

# Far legs (darker, behind body)
stroke("M168,58 L186,70 L200,77", FUR_DARK, 5.5)
stroke("M118,55 L102,70 L88,70 L80,75", FUR_DARK, 5.5)

# Tail
stroke("M104,45 C90,41 80,50 70,42", FUR, 3.6)

# Body
fill("M102,47 C102,38 112,33 126,35 C140,37 150,38 162,36 C174,34 184,40 184,50 "
     "C184,60 176,66 164,65 C150,64 140,54 130,53 C122,52 118,60 108,58 C101,56 102,51 102,47 Z", FUR)
# Belly highlight
fill("M150,58 C158,63 168,64 176,60 C172,64 164,66 156,63 Z", FUR_LIGHT)

# Near legs: thick thigh, slim lower leg
stroke("M174,56 L190,64", FUR, 8)
stroke("M190,64 L208,68", FUR, 5)
stroke("M112,52 L96,63", FUR, 9)
stroke("M96,63 L82,60 L72,64", FUR, 5)

# Neck and head
stroke("M174,42 L190,27", FUR, 11)
fill("M186,23 C189,15 201,14 206,19 L219,27 C221,29 220,33 216,33 L198,32 C189,31 184,28 186,23 Z", FUR)
# Ear folded back
fill("M193,19 C188,13 181,14 179,18 C184,19 188,21 192,23 Z", FUR_DARK)
# Tongue, eye, nose
fill("M206,32 C207,38 212,38 213,32 Z", PINK)
fill(ellipse(200.5, 22, 1.7, 1.7), INK)
fill(ellipse(201.1, 21.4, 0.5, 0.5), "#FFFFFF")
fill(ellipse(218.5, 29.5, 1.6, 1.4), INK)
# Collar with tag
stroke("M180,33 L185,42", MINT_DARK, 4.2)
fill(ellipse(185, 45, 1.9, 1.9), SUN)

# Ball with motion lines
for (x1, y, x2) in [(270, 46, 282), (266, 54, 282), (272, 62, 284)]:
    stroke(f"M{x1},{y} L{x2},{y}", MINT_DARK, 2.2, 0.7)
fill(ellipse(300, 54, 11, 11), BALL)
stroke("M292,46 C297,51 297,57 292,62", BALL_SEAM, 1.8)
stroke("M308,46 C303,51 303,57 308,62", BALL_SEAM, 1.8)

def svg():
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W*4}" height="{H*4}">',
           f'<rect width="{W}" height="{H}" fill="#FBF6EE"/>']
    for k, d, c, x in E:
        if k == "fill":
            out.append(f'<path d="{d}" fill="{c}" fill-opacity="{x}"/>')
        else:
            out.append(f'<path d="{d}" fill="none" stroke="{c}" stroke-opacity="{x[1]}" stroke-width="{x[0]}" stroke-linecap="round" stroke-linejoin="round"/>')
    out.append("</svg>")
    return "\n".join(out)

def vd():
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Header illustration: greyhound chasing a ball. Generated by art/header_greyhound.py; edit the script, not this file. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           f'    android:width="{W}dp"', f'    android:height="{H}dp"',
           f'    android:viewportWidth="{W}"', f'    android:viewportHeight="{H}">']
    for k, d, c, x in E:
        if k == "fill":
            alpha = f'\n        android:fillAlpha="{x}"' if x != 1.0 else ""
            out.append(f'    <path\n        android:fillColor="{c}"{alpha}\n        android:pathData="{d}" />')
        else:
            alpha = f'\n        android:strokeAlpha="{x[1]}"' if x[1] != 1.0 else ""
            out.append(f'    <path\n        android:strokeColor="{c}"{alpha}\n        android:strokeWidth="{x[0]}"\n'
                       f'        android:strokeLineCap="round"\n        android:strokeLineJoin="round"\n        android:pathData="{d}" />')
    out.append("</vector>")
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    open("art/header_greyhound.svg", "w").write(svg())
    open("app/src/main/res/drawable/header_greyhound.xml", "w").write(vd())
